#!/usr/bin/env python3
"""Read out/<arm>/run*/summary.json and write out/RESULTS.md and out/results.json.

Usage: aggregate.py OUT_DIR
Nothing here is judged by hand: every column comes from the per-run summaries.
"""

import glob
import json
import os
import sys


def load(out_dir):
    arms = {}
    for path in sorted(glob.glob(os.path.join(out_dir, "*", "run*", "summary.json"))):
        with open(path) as handle:
            s = json.load(handle)
        arms.setdefault(s["arm"]["id"], []).append(s)
    return arms


def span(values, fmt="%.1f"):
    values = [v for v in values if v is not None]
    if not values:
        return "-"
    lo, hi = min(values), max(values)
    return (fmt % lo) if lo == hi else (fmt + "-" + fmt) % (lo, hi)


def agreement(runs):
    sigs = [r.get("afterSignatureSha256") for r in runs]
    if not sigs or any(s is None for s in sigs):
        return "n/a"
    distinct = len(set(sigs))
    return "%d/%d same" % (len(sigs), len(sigs)) if distinct == 1 else "%d distinct of %d" % (distinct, len(sigs))


def row(arm_id, runs):
    first = runs[0]
    arm = first["arm"]
    undo = [r.get("undo", {}) for r in runs]
    new_actions = sorted({"/".join(u.get("newActions", [])) or "(none)" for u in undo})
    restore = sorted({str(r.get("undoStepsToRestore")) for r in runs})
    blocked = [r["blocked"]["step"] for r in runs if "blocked" in r]
    expected = [all(r.get("expectedTextPresent", {}).values()) for r in runs if "expectedTextPresent" in r]
    readback = all(r.get("positionReadbackAsExpected") for r in runs)
    listener = [len(r.get("listenerRequests", [])) for r in runs if "listenerRequests" in r]
    tarpit = [[(e["event"], e["dt"]) for e in r.get("tarpit", [])] for r in runs if "tarpit" in r]
    return {
        "arm": arm_id, "position": arm["position"], "corpus": arm["corpus"], "mime": arm["mime"],
        "lang": arm["lang"], "runs": len(runs),
        "returned": sorted({str(r.get("pasteReturned")) for r in runs}),
        "callMs": span([r.get("pasteCallMs") for r in runs]),
        "paintMs": span([r.get("paintMs") for r in runs]),
        "undoDelta": sorted({(u.get("countAfter", 0) - u.get("countBefore", 0)) for u in undo}),
        "undoActions": new_actions, "undoStepsToRestore": restore,
        "afterSameAsBefore": sorted({str(r.get("afterSameAsBefore")) for r in runs}),
        "agreement": agreement(runs), "blocked": blocked,
        "expectedText": ("%d/%d" % (sum(expected), len(expected))) if expected else "-",
        "positionReadbackOK": readback,
        "threadTextEncoding": sorted({r.get("threadTextEncoding") for r in runs}),
        "callbacksListed": span([r.get("callbacks", {}).get("listed") for r in runs], "%d"),
        "coreLogCallbacks": span([r.get("callbacks", {}).get("coreLog", {}).get("count") for r in runs], "%d"),
        "dialogLikeCallbacks": sorted({n for r in runs for n in r.get("callbacks", {}).get("dialogLike", [])}),
        "listenerRequests": listener, "tarpitEvents": tarpit,
        "afterHumanRun1": first.get("afterHuman", ""),
    }


def main(argv):
    out_dir = argv[1]
    arms = load(out_dir)
    rows = [row(k, v) for k, v in arms.items()]
    order = {a: i for i, a in enumerate(arms)}
    rows.sort(key=lambda r: (r["arm"].split("-")[0], order[r["arm"]]))
    with open(os.path.join(out_dir, "results.json"), "w") as handle:
        json.dump(rows, handle, ensure_ascii=False, indent=1)
    lines = ["# Results (generated by tool/aggregate.py from out/*/run*/summary.json)", "",
             "| arm | LANG | mime | returned | call ms | undo +n (action) | Undo to restore | "
             "3 runs | expected text | readback ok | enc | listed cb | CORE_LOG cb | blocked |",
             "|---|---|---|---|---|---|---|---|---|---|---|---|---|---|"]
    for r in rows:
        lines.append("| %s | %s | %s | %s | %s | %s (%s) | %s | %s | %s | %s | %s | %s | %s | %s |" % (
            r["arm"], r["lang"], r["mime"], ",".join(r["returned"]), r["callMs"],
            ",".join(map(str, r["undoDelta"])), "; ".join(r["undoActions"]),
            ",".join(r["undoStepsToRestore"]), r["agreement"], r["expectedText"],
            "yes" if r["positionReadbackOK"] else "NO", ",".join(map(str, r["threadTextEncoding"])),
            r["callbacksListed"], r["coreLogCallbacks"], ",".join(r["blocked"]) or "-"))
    lines += ["", "## Structure after the paste (run 1 of each arm; tool/md_structure.py)", ""]
    for r in rows:
        lines += ["### " + r["arm"], "", "```", r["afterHumanRun1"], "```", ""]
        if r["listenerRequests"]:
            lines += ["listener requests per run: %s" % r["listenerRequests"], ""]
        if r["tarpitEvents"]:
            lines += ["tarpit events per run (event, s since process start): %s" % r["tarpitEvents"], ""]
    with open(os.path.join(out_dir, "RESULTS.md"), "w") as handle:
        handle.write("\n".join(lines) + "\n")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv))
