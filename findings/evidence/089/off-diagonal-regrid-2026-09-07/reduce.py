CONTROL_CASE = "d1-anchors.odt"

# Points supporting N1/N2 (section 5.1) -- the "owed" off-diagonal half.
# The task file's section 1.1 summary sentence says "six owed" (counting
# only Row A literally), but sections 5.1/5.3 (C2: "B1 or B2 does not open.
# N2 falls.") substantively treat B1/B2 as owed points whose failure retires
# N2. This script follows the substantive, repeatedly-confirmed definition
# (all of Row A + Row B, eight points) rather than the undercounted summary
# noun phrase. This is a genuine textual inconsistency in the task file,
# named here rather than silently picked one way.
OWED = ["A1", "A2", "A3", "A4", "A5", "A6", "B1", "B2"]
ROW_A = ["A1", "A2", "A3", "A4", "A5", "A6"]
ROW_B = ["B1", "B2"]
ALL_TEN = ROW_A + ROW_B + ["K1", "K2"]

VOID = "VOID"          # zero non-void repeats seen for this point
REPRODUCES = "REPRODUCES"
CONTRADICTS = "CONTRADICTS"
SPLITS = "SPLITS"
ANOMALOUS = "ANOMALOUS"  # opened truthy but the full REPRODUCES predicate did not hold -- unanticipated, named rather than folded in


def classify_repeat(case_entry, banked_verdict):
    """Section 4.1's per-repeat categorical predicate. Returns one of:
    REPRODUCES, CONTRADICTS, ANOMALOUS, "VOID_ABSENT", "VOID_OTHER".
    The two VOID_* strings are repeat-level; they make that repeat void for
    that point and do not count toward N (section 4.1's ABSENT MEASUREMENT
    rule, and the TIMEOUT "anything else" rule).
    """
    opened = case_entry.get("opened")
    error = case_entry.get("error")
    elapsed_ms = case_entry.get("elapsedMs")

    # The general ABSENT MEASUREMENT carve-out (section 4.1, third paragraph):
    # elapsedMs: null, opened: false, error: null -- void, not a failure.
    if not opened and error is None and elapsed_ms is None:
        return "VOID_ABSENT"

    if banked_verdict == "opened":
        if opened:
            parts = opened.get("parts") if isinstance(opened, dict) else None
            tile = case_entry.get("tile") or {}
            if error is None and parts == 2 and tile.get("ok") is True:
                return REPRODUCES
            return ANOMALOUS
        return CONTRADICTS

    if banked_verdict == "timeout":
        if opened:
            return CONTRADICTS
        if (
            isinstance(error, dict)
            and error.get("code") == "TIMEOUT"
            and "180000" in str(error.get("message", ""))
            and isinstance(elapsed_ms, (int, float))
            and 180000 <= elapsed_ms <= 182000
        ):
            return REPRODUCES
        return "VOID_OTHER"

    raise ValueError(f"unknown banked_verdict {banked_verdict!r}")


def aggregate_point(classifications):
    """Section 4.1 last paragraph: REPRODUCES iff all non-void repeats
    reproduce; CONTRADICTS iff all contradict; SPLITS otherwise. A point
    with zero non-void repeats is VOID (not vacuously REPRODUCES) -- this
    guard is this script's own addition, named here: the task file does not
    spell out the zero-repeat case, and treating an empty set as vacuously
    "all reproduce" would silently manufacture a positive result out of no
    data at all.
    """
    non_void = [c for c in classifications if c not in ("VOID_ABSENT", "VOID_OTHER")]
    if not non_void:
        return VOID
    if any(c == ANOMALOUS for c in non_void):
        return ANOMALOUS
    if all(c == REPRODUCES for c in non_void):
        return REPRODUCES
    if all(c == CONTRADICTS for c in non_void):
        return CONTRADICTS
    return SPLITS


def timing_band(r):
    """Section 4.2's table. r = median(elapsedMs today) / banked elapsedMs."""
    if r is None:
        return None
    if 0.5 <= r <= 2.0:
        return "reproduces the banked figure"
    if (0.25 <= r < 0.5) or (2.0 < r <= 4.0):
        return "outside the band, same order of magnitude"
    return "does not reproduce the banked figure"


def load_reports(reports_dir):
    reports = []
    for path in sorted(Path(reports_dir).glob("*.json")):
        name = path.name
        if name in ("identity.json", "regrid-verdict.json"):
            continue
        if name.startswith("redcase-"):
            continue
        try:
            data = json.loads(path.read_text())
        except Exception as exc:  # noqa: BLE001 -- report this, do not swallow it
            raise SystemExit(f"reduce.py: could not parse {path} as JSON: {exc}")
        if "page" not in data or "inputs" not in data:
            raise SystemExit(f"reduce.py: {path} does not look like a probe report (missing page/inputs)")
        reports.append((str(path), data))
    return reports


def evaluate_gates(report, identity):
    """Section 4.5's per-invocation non-vacuity gate, plus RC-1 (both
    outcomes seen) evaluated in band as its last bullet says.
    Returns (void: bool, reasons: [str], mismatches: [str], both_outcomes_seen: bool).
    """
    reasons = []
    mismatches = []

    if report.get("verdict", {}).get("controlOdtOpened") is not True:
        reasons.append("verdict.controlOdtOpened != true")

    if report.get("openTimeoutMs") != 180000:
        reasons.append(f"openTimeoutMs != 180000 (got {report.get('openTimeoutMs')!r})")

    fixture_hashes = identity.get("fixtureHashes", {}) if identity else {}
    for inp in report.get("inputs", []):
        case = inp.get("case")
        expected = fixture_hashes.get(case)
        if expected is None:
            mismatches.append(inp.get("path", case))
            reasons.append(f"case {case!r} is not in identity.json's fixtureHashes")
        elif inp.get("sha256") != expected:
            mismatches.append(inp.get("path", case))
            reasons.append(f"sha256 mismatch for case {case!r}: report has {inp.get('sha256')!r}, identity.json has {expected!r}")

    fatal = report.get("progress", {}).get("fatal")
    if fatal is not None:
        reasons.append(f"progress.fatal != null (got {fatal!r})")

    sheet_cases = [c for c in report.get("page", {}).get("cases", []) if c.get("kind") == "spreadsheet"]
    opened_vals = [bool(c.get("opened")) for c in sheet_cases]
    both_outcomes_seen = (True in opened_vals) and (False in opened_vals)
    if not both_outcomes_seen:
        reasons.append(
            "RC-1 failed: bothOutcomesSeen=false "
            f"(spreadsheet cases in this invocation: {[ (c.get('name'), bool(c.get('opened'))) for c in sheet_cases]})"
        )

    return (len(reasons) > 0), reasons, mismatches, both_outcomes_seen


def main():
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--identity", required=True, help="path to identity.json")
    ap.add_argument("--reports-dir", required=True, help="directory containing A-*.json / B-*.json reports")
    ap.add_argument("--out", required=True, help="path to write regrid-verdict.json")
    args = ap.parse_args()

    identity = json.loads(Path(args.identity).read_text())
    reports = load_reports(args.reports_dir)

    if not reports:
        result = {"status": "no-reports"}
        Path(args.out).write_text(json.dumps(result, indent=2) + "\n")
        print(json.dumps(result))
        return 1

    # --- section 4.5 gates, per report -------------------------------------------------
    per_report = []
    for path, report in reports:
        void, reasons, mismatches, both = evaluate_gates(report, identity)
        per_report.append({
            "path": path,
            "void": void,
            "reasons": reasons,
            "mismatches": mismatches,
            "bothOutcomesSeen": both,
            "controlOdtOpened": report.get("verdict", {}).get("controlOdtOpened"),
            "openTimeoutMs": report.get("openTimeoutMs"),
            "report": report,
        })

    non_void = [r for r in per_report if not r["void"]]

    if not non_void:
        all_mismatches = sorted({m for r in per_report for m in r["mismatches"]})
        all_reasons = []
        for r in per_report:
            for reason in r["reasons"]:
                if reason not in all_reasons:
                    all_reasons.append(reason)
        result = {
            "status": "void",
            "reason": "; ".join(all_reasons) if all_reasons else "all supplied reports failed section 4.5's gate",
            "mismatches": all_mismatches,
            "voidedReports": [{"path": r["path"], "reasons": r["reasons"]} for r in per_report],
        }
        Path(args.out).write_text(json.dumps(result, indent=2) + "\n")
        print(json.dumps(result))
        return 1

    # --- per-point classification, over non-void reports only --------------------------
    point_repeats = {pid: [] for pid in ALL_TEN}
    for entry in non_void:
        report = entry["report"]
        for case in report.get("page", {}).get("cases", []):
            name = case.get("name")
            for pid, spec in POINTS.items():
                if spec["case"] == name:
                    classification = classify_repeat(case, spec["banked_verdict"])
                    point_repeats[pid].append({
                        "reportPath": entry["path"],
                        "classification": classification,
                        "elapsedMs": case.get("elapsedMs"),
                        "workerCrashed": next(
                            (s.get("workerCrashed") for s in report.get("verdict", {}).get("spreadsheetsOpened", [])
                             if s.get("name") == name),
                            None,
                        ),
                        "warnings": [w.get("message") for w in case.get("warnings", [])],
                        "opened_parts": (case.get("opened") or {}).get("parts") if isinstance(case.get("opened"), dict) else None,
                        "tile_ok": (case.get("tile") or {}).get("ok"),
                        "error": case.get("error"),
                    })

    control_repeats = []
    for entry in non_void:
        report = entry["report"]
        for case in report.get("page", {}).get("cases", []):
            if case.get("name") == CONTROL_CASE:
                control_repeats.append({
                    "reportPath": entry["path"],
                    "elapsedMs": case.get("elapsedMs"),
                    "opened_truthy": bool(case.get("opened")),
                })

    points_out = {}
    point_verdicts = {}
    for pid, spec in POINTS.items():
        repeats = point_repeats[pid]
        classifications = [r["classification"] for r in repeats]
        verdict = aggregate_point(classifications)
        point_verdicts[pid] = verdict

        r_value = None
        band = None
        if spec["banked_verdict"] == "opened":
            today_elapsed = [r["elapsedMs"] for r in repeats if isinstance(r["elapsedMs"], (int, float))]
            if today_elapsed:
                banked_ref = spec["banked_elapsed_ms"][0]
                r_value = statistics.median(today_elapsed) / banked_ref
                band = timing_band(r_value)

        points_out[pid] = {
            "case": spec["case"],
            "index": spec["index"],
            "index2": spec["index2"],
            "row": spec["row"],
            "bankedVerdict": spec["banked_verdict"],
            "bankedElapsedMs": spec["banked_elapsed_ms"],
            "bankedSource": spec["source"],
            "note": spec.get("note"),
            "repeats": repeats,
            "nonVoidRepeatCount": len([c for c in classifications if c not in ("VOID_ABSENT", "VOID_OTHER")]),
            "totalRepeatCount": len(classifications),
            "r": r_value,
            "band": band,
            "pointVerdict": verdict,
        }

    # --- E1: either anchor "fails to open"/"opens" in some individual repeat -----------
    e1_events = []
    for pid in ("K1", "K2"):
        for rep in point_repeats[pid]:
            if rep["classification"] == CONTRADICTS:
                e1_events.append({"point": pid, "reportPath": rep["reportPath"], "classification": rep["classification"]})
    e1_fired = len(e1_events) > 0

    # --- E2: two or more owed points SPLIT ---------------------------------------------
    split_owed = [pid for pid in OWED if point_verdicts[pid] == SPLITS]
    e2_fired = len(split_owed) >= 2

    # --- E3: for any point that opened in every (non-void) repeat, spread > 4.0x -------
    e3_events = []

    def check_spread(label, elapsed_values):
        vals = [v for v in elapsed_values if isinstance(v, (int, float))]
        if len(vals) < 2:
            return
        spread = max(vals) / min(vals)
        if spread > 4.0:
            e3_events.append({"point": label, "spread": spread, "values": vals})

    for pid in ALL_TEN:
        if point_verdicts[pid] == REPRODUCES:
            check_spread(pid, [r["elapsedMs"] for r in point_repeats[pid]])
    if control_repeats and all(c["opened_truthy"] for c in control_repeats):
        check_spread("control(d1-anchors.odt)", [c["elapsedMs"] for c in control_repeats])
    e3_fired = len(e3_events) > 0

    triggers = {
        "E1": {"fired": e1_fired, "events": e1_events},
        "E2": {"fired": e2_fired, "splitPoints": split_owed},
        "E3": {"fired": e3_fired, "events": e3_events},
    }

    # --- outcome selection, in the order fixed by section 1.2 ---------------------------
    outcome = None
    trigger_clause = None

    if e1_fired:
        outcome = "E"
        trigger_clause = f"E1 -- anchor contradicted in an individual repeat: {e1_events}"
    elif e2_fired:
        outcome = "E"
        trigger_clause = f"E2 -- two or more owed points SPLIT: {split_owed}"
    elif e3_fired:
        outcome = "E"
        trigger_clause = f"E3 -- elapsedMs spread exceeds 4.0x for a point that opened in every repeat: {e3_events}"
    else:
        contra_points = [pid for pid in OWED if point_verdicts[pid] == CONTRADICTS]
        if contra_points:
            outcome = "C"
            subcases = set()
            for pid in contra_points:
                if pid in ("A1", "A2", "A3", "A4", "A5"):
                    subcases.add("C1")
                if pid in ("B1", "B2"):
                    subcases.add("C2")
                if pid == "A6":
                    subcases.add("C3")
            trigger_clause = (
                f"C ({','.join(sorted(subcases))}) -- point(s) {contra_points} "
                "CONTRADICTED their banked verdict unanimously across their repeats"
            )
        else:
            split_points = [pid for pid in OWED if point_verdicts[pid] == SPLITS]
            if split_points:
                outcome = "S"
                trigger_clause = f"S -- point(s) {split_points} SPLIT across repeats (anchors unanimous, E1 did not fire)"
            else:
                reproduces_all_ten = all(point_verdicts[pid] == REPRODUCES for pid in ALL_TEN)
                control_ok = bool(control_repeats) and all(c["opened_truthy"] for c in control_repeats)
                no_invocation_void = all(not r["void"] for r in per_report)
                if reproduces_all_ten and control_ok and no_invocation_void:
                    outcome = "R"
                    trigger_clause = (
                        "R -- all ten named points REPRODUCE unanimously, the ODT control opened in every "
                        "invocation, and no invocation was void"
                    )
                else:
                    outcome = "PARTIAL"
                    missing = [pid for pid in ALL_TEN if point_verdicts[pid] == VOID]
                    anomalous = [pid for pid in ALL_TEN if point_verdicts[pid] == ANOMALOUS]
                    trigger_clause = (
                        "PARTIAL is not one of the five canonical outcome letters in section 1.2. "
                        "It is emitted when none of E/C/S fired but the input does not cover enough of "
                        "the ten named points (plus a clean control, plus no voided invocation) to "
                        f"satisfy Outcome R's own completeness requirement. pointsWithNoData={missing}, "
                        f"anomalousPoints={anomalous}, controlOk={control_ok}, "
                        f"noInvocationVoid={no_invocation_void}"
                    )

    result = {
        "schemaNote": SCHEMA_NOTE,
        "identityFile": args.identity,
        "reportsDir": args.reports_dir,
        "perReport": [
            {
                "path": r["path"],
                "void": r["void"],
                "reasons": r["reasons"],
                "mismatches": r["mismatches"],
                "bothOutcomesSeen": r["bothOutcomesSeen"],
                "controlOdtOpened": r["controlOdtOpened"],
                "openTimeoutMs": r["openTimeoutMs"],
            }
            for r in per_report
        ],
        "points": points_out,
        "triggers": triggers,
        "outcome": outcome,
        "triggerClause": trigger_clause,
    }
    Path(args.out).write_text(json.dumps(result, indent=2, default=str) + "\n")
    print(f"OUTCOME: {outcome}")
    print(f"TRIGGER: {trigger_clause}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
