#!/usr/bin/env python3
"""reduce.py -- the form-two instrument for
TASK-2026-09-07-089-off-diagonal-regrid.md (see that file for the full
specification; section numbers below refer to it).

Reads probe_ods_on_profile.py report files (A-<n>-report.json / B-<n>-report.json)
plus identity.json, and derives:
  - a per-repeat categorical verdict for each of the ten named grid points
    (A1-A6, B1, B2, K1, K2), per section 4.1;
  - the timing band for points banked as "opened", per section 4.2;
  - the per-point verdict (REPRODUCES / CONTRADICTS / SPLITS / VOID);
  - the outcome letter (E / C / S / R / V) and the trigger clause it fired
    on, evaluated in the order fixed by section 1.2.

This script is a re-derivation over existing report files. It does not talk
to a browser, does not open anything, and does not write anywhere except the
--out path it is given. It contains no threshold that is not written in
TASK-2026-09-07-089-off-diagonal-regrid.md.

Every number this script treats as "banked" (POINTS below) is copied
verbatim from section 2 of that task file. The point list itself is a hand
enumeration (form three, per that file's own section 1.1) -- it is the scope
of a measurement, not a claim that these are the only points that matter.

A note on completeness: Outcome R (section 1.2) requires that all ten named
points plus the ODT control are present, non-void, and unanimous. If this
script is run over a report set that only covers some of the ten points
(as the section 6 self-tests deliberately do, by design, using a single
report), it cannot legitimately emit "R" -- R's own definition requires full
coverage. In that case this script reports status "PARTIAL" (not one of the
five canonical outcome letters) and names exactly which points have no data,
rather than inventing a false "R". A canonical outcome letter is only ever
emitted when its own trigger, as written in section 1.2, actually fires.
"""
