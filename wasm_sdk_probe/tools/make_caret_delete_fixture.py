#!/usr/bin/env python3
"""The fixture of tests/caret_delete_witness_test.cpp, generated from the committed native G run
(SPEC-M3-ordered-commands 15.1, 15.7; fable ruling 2 2.1: "the recorded tuples of the native run are
committed as its fixture, labels derived from the saved text").

Usage:
  python3 -I tools/make_caret_delete_fixture.py [--evidence DIR] [--output FILE]
  python3 -I tools/make_caret_delete_fixture.py --check     regenerate and compare with the committed file

Input: every uni1 cell of ev/native/caret-delete-witness/out (run_arms.py --arms-set g, OC_A11Y=1). seq cells
are left out on purpose: in the threaded topology the at-return read can precede the posted key (README), and
the decider is for C only.

The label is not the decider's: per cell, the characters the saved document lost against its fixture (the
sum of paragraph text lengths, fixture minus saved, read_g.py's oracle). The arms are all-or-nothing by
construction, so a cell that lost as many characters as it has ops labels every op `deleted`, a cell that
lost none labels every op `noop`, and anything else is refused here rather than guessed.

Output: one header line per input file (`# sha256 PATH`), then one tab-separated line per op:
  arm round op key label undoBefore undoAfter beforePos beforeContent afterPos afterContent
with every string field hex-encoded UTF-8 (`=` for an empty string, `-` for a read that is absent). Positions are getA11yFocusedParagraph's
`position`; the fixture carries no list prefix (none of the G fixtures has a list).
"""
import argparse
import gzip
import hashlib
import json
import pathlib
import sys
import xml.etree.ElementTree as ET

ROOT = pathlib.Path(__file__).resolve().parents[2]
EVIDENCE = ROOT / 'findings/evidence/link-batch-v23/native/caret-delete-witness'
FIXTURES = ROOT / 'findings/evidence/link-batch-v23/native/ordered-commands/fixtures'
OUTPUT = ROOT / 'wasm_sdk_probe/tests/caret_delete_witness_fixture.tsv'
TEXT_NS = 'urn:oasis:names:tc:opendocument:xmlns:text:1.0'
KEYS = {'K1283': 'backspace', 'K1286': 'delete'}


def text_length(xml_bytes):
    root = ET.fromstring(xml_bytes)
    return sum(len(''.join(el.itertext())) for el in root.iter()
               if el.tag in ('{%s}p' % TEXT_NS, '{%s}h' % TEXT_NS))


def hexed(text):
    return '-' if text is None else (text.encode('utf-8').hex() or '=')


def a11y(text):
    d = json.loads(text)
    return int(d['position']), d['content']


def generate(evidence, fixtures):
    out = evidence / 'out'
    arms = json.loads((out / 'arms.json').read_text())
    inputs, rows = [out / 'arms.json'], []
    for arm in arms:
        name = arm['name']
        fixture = fixtures / f"{arm['fixture']}.fodt"
        inputs.append(fixture)
        cells = sorted((out / name).glob('uni1-r*.jsonl'), key=lambda p: int(p.stem.split('-r')[1]))
        if not cells:
            raise SystemExit(f'{name}: no uni1 cell under {out / name} (the generator must not emit an empty fixture)')
        for cell in cells:
            rnd = int(cell.stem.split('-r')[1])
            saved = cell.with_name(f'uni1-r{rnd}.fodt.gz')
            inputs += [cell, saved]
            recs = [json.loads(x) for x in cell.read_text().splitlines() if x.strip()]
            measured = [r for r in recs if r.get('rec') == 'measured']
            if len(measured) != 1:
                raise SystemExit(f'{cell}: {len(measured)} measured records')
            ops = measured[0]['ops']
            lost = text_length(fixture.read_bytes()) - text_length(gzip.decompress(saved.read_bytes()))
            if lost not in (0, len(ops)):
                raise SystemExit(f'{cell}: lost {lost} of {len(ops)} ops; the label cannot be derived per op')
            label = 'deleted' if lost == len(ops) and lost else 'noop'
            for i, op in enumerate(ops, 1):
                if op['op'] not in KEYS:
                    raise SystemExit(f'{cell} op {i}: {op["op"]} is not a caret delete')
                bp, bc = a11y(op['atStart']['a11y'])
                ap, ac = a11y(op['atReturn']['a11y'])
                rows.append('\t'.join([name, str(rnd), str(i), KEYS[op['op']], label,
                                       hexed(op['atStart']['undo']), hexed(op['atReturn']['undo']),
                                       str(bp), hexed(bc), str(ap), hexed(ac)]))
    inputs = list(dict.fromkeys(inputs))
    head = [f'# {hashlib.sha256(p.read_bytes()).hexdigest()} {p.relative_to(ROOT)}' for p in inputs]
    return '\n'.join(['# generated by wasm_sdk_probe/tools/make_caret_delete_fixture.py; do not edit'] + head + rows) + '\n'


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('--evidence', default=str(EVIDENCE))
    ap.add_argument('--fixtures', default=str(FIXTURES))
    ap.add_argument('--output', default=str(OUTPUT))
    ap.add_argument('--check', action='store_true')
    a = ap.parse_args()
    text = generate(pathlib.Path(a.evidence), pathlib.Path(a.fixtures))
    out = pathlib.Path(a.output)
    if a.check:
        if not out.exists() or out.read_text() != text:
            print(f'{out} differs from what the committed G run generates', file=sys.stderr)
            return 1
        return 0
    out.write_text(text)
    print(f'{out}: {len(text.splitlines())} lines')
    return 0


if __name__ == '__main__':
    sys.exit(main())
