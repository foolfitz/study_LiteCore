#!/usr/bin/env python3
"""Build R0's case files (SPEC-M3-paragraph-merge 4.2) as the union of the case
files rounds four and six ran, so R0's population is the listed files and not
a hand-copied list.  A case id that appears twice must be the same row in both
files; a conflict is an error, not a choice.

Usage: merge_r0_cases.py [--check]   (--check: exit 1 if the outputs differ)
"""
from __future__ import annotations

import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent.parent / "test-docs" / "merge"

# Output file -> the source case files, in order.  Rounds four (round-g-*) and
# six (round-i-*), plus R0's own typed cases (M2-1b's native reference).
UNIONS = {
    "r0-boundaries.cases.tsv": ["round-g-boundaries.cases.tsv", "round-i-boundaries.cases.tsv",
                                "round-i-tables.cases.tsv", "round-r0-typed.cases.tsv"],
    "r0-indent.cases.tsv": ["round-g-indent.cases.tsv"],
    "r0-pmpc.cases.tsv": ["round-g-pmpc.cases.tsv", "round-i-pmpc.cases.tsv"],
}


def rows(path: Path) -> list[str]:
    out = []
    for line in path.read_text(encoding="utf-8").splitlines():
        if line and not line.startswith("#"):
            out.append(line)
    return out


def build(sources: list[str]) -> str:
    seen: dict[str, tuple[str, str]] = {}
    order: list[str] = []
    for name in sources:
        for row in rows(HERE / name):
            case = row.split("\t", 1)[0]
            if case in seen:
                if seen[case][0] != row:
                    raise SystemExit(f"conflict for {case}: {seen[case][1]} vs {name}")
                continue
            seen[case] = (row, name)
            order.append(case)
    if not order:
        raise SystemExit(f"no cases in {sources}")
    header = "# Generated by tools/merge_r0_cases.py from: " + ", ".join(sources) + "\n"
    return header + "".join(seen[c][0] + "\n" for c in order)


def main() -> int:
    check = "--check" in sys.argv[1:]
    stale = False
    for out, sources in UNIONS.items():
        text = build(sources)
        path = HERE / out
        if check:
            if not path.exists() or path.read_text(encoding="utf-8") != text:
                print(f"stale: {out}")
                stale = True
        else:
            path.write_text(text, encoding="utf-8")
            print(f"{out}: {text.count(chr(10)) - 1} cases")
    return 1 if stale else 0


if __name__ == "__main__":
    sys.exit(main())
