def synthetic() -> dict:
    tile = lambda sha: {"sha256": sha, "widthTwipsType": "number", "heightTwipsType": "number",  # noqa: E731
                        "sizeChangedType": "boolean", "documentSizeChanged": False}
    def sheet(k, text_sha, tile_sha):
        return {"part": k, "switch": {"readBack": k}, "readBack": k, "error": None,
                "text": {"sha256": text_sha, "length": 1, "partAfter": 0, "currentPartBefore": 0,
                         "selectAllConfirmed": True},
                "tiles": [tile(tile_sha), {**tile(tile_sha), "documentSizeChanged": False}]}
    def opened(path, names, sheets):
        return {"kind": "corpus", "name": Path(path).name, "inputSha256": "sha-" + path, "engineCreated": True,
                "opened": {"atMs": 900}, "viewReadyAtMs": 900, "workerCrashed": False, "error": None,
                "refused": None, "state": {"documentType": "spreadsheet", "parts": len(names),
                                           "partNames": names, "nameSpoofed": False},
                "handleFields": {"documentType": "spreadsheet", "inputSuffix": ".ods"},
                "sheets": sheets, "reselect": {"current": 0, "readBack": 0}, "afterRefusals": 0,
                "sessionRefusal": {"code": "PART_OUT_OF_RANGE"}, "engineRefusal": {"code": "INVALID_ARGUMENT"},
                "stages": [{"name": "open.begin", "sbrk": 293_000_000},
                           {"name": "document-destroy-enter", "sbrk": 300_000_000}]}
    def staged(path, names, texts, expect="opens", cells=1):
        return {"path": path, "sha256": "sha-" + path, "sheets": len(names), "sheetNames": names,
                "expect": expect, "expectedFrom": "generator", "cells": cells,
                "expectedSheets": [{"name": n, "textSha256": t, "textLength": 1, "empty": t == "E"}
                                   for n, t in zip(names, texts)]}
    report = {
        "fullCorpus": False,
        "corpusFiles": {"ladder/empty-one-sheet.ods": "sha-ladder/empty-one-sheet.ods",
                        DISTINCT: "sha-" + DISTINCT, IDENTICAL: "sha-" + IDENTICAL,
                        "upstream/password.ods": "sha-upstream/password.ods"},
        "manifestEntries": [{"path": p, "sha256": "sha-" + p} for p in
                            ("ladder/empty-one-sheet.ods", DISTINCT, IDENTICAL, "upstream/password.ods")],
        "staged": [staged(EMPTY_CONTROL, ["Sheet1"], ["E"], cells=0),
                   staged(DISTINCT, ["Alpha", "Beta", "Gamma"], ["a", "b", "c"]),
                   staged(IDENTICAL, ["One", "Two", "Three"], ["s", "s", "s"]),
                   staged("upstream/password.ods", [], [], expect="refused")],
        "cases": [opened(EMPTY_CONTROL, ["Sheet1"], [sheet(0, "E", "empty")]),
                  opened(DISTINCT, ["Alpha", "Beta", "Gamma"],
                         [sheet(0, "a", "t0"), sheet(1, "b", "t1"), sheet(2, "c", "t2")]),
                  opened(IDENTICAL, ["One", "Two", "Three"],
                         [sheet(0, "s", "same"), sheet(1, "s", "same"), sheet(2, "s", "same")]),
                  {"kind": "corpus", "name": "password.ods", "inputSha256": "sha-upstream/password.ods",
                   "engineCreated": False, "refused": {"code": "ENCRYPTED_DOCUMENT"}},
                  {"kind": "control-odt", "refused": {"code": "DOCUMENT_TYPE_REFUSED"},
                   "handleFields": {"documentType": "text"}}],
    }
    # The switch read-backs of the synthetic sheets follow their part; partAfter is the part before.
    return report


def selftest() -> int:
    base = synthetic()

    def case(b, path):
        return next(c for c in b["cases"] if c.get("inputSha256") == "sha-" + path)

    mutations = [
        ("E1", "a corpus file without a manifest entry",
         lambda b: b["corpusFiles"].update({"ladder/zzz.ods": "sha-z"})),
        ("E1", "an empty corpus directory", lambda b: b.update(corpusFiles={})),
        ("E1", "a staged entry with no record", lambda b: b["cases"].pop(1)),
        ("E2", "the ODT control passes as a spreadsheet",
         lambda b: b["cases"][-1].update(refused=None, handleFields={"documentType": "spreadsheet"})),
        ("E2", "the three-sheet file reports 1 part", lambda b: case(b, DISTINCT)["state"].update(parts=1)),
        ("E2", "the name was spoofed", lambda b: case(b, DISTINCT)["state"].update(nameSpoofed=True)),
        ("E2", "the input file was .odt", lambda b: case(b, DISTINCT)["handleFields"].update(inputSuffix=".odt")),
        ("E2", "view-ready after 60 s", lambda b: case(b, DISTINCT).update(viewReadyAtMs=60_001)),
        ("E2", "the encrypted file reached an engine",
         lambda b: case(b, "upstream/password.ods").update(engineCreated=True)),
        ("E2", "the encrypted file refused generically",
         lambda b: case(b, "upstream/password.ods").update(refused={"code": "LOK_ERROR"})),
        ("E3", "two sheets' texts swapped", lambda b: (
            case(b, DISTINCT)["sheets"][0]["text"].update(sha256="b"),
            case(b, DISTINCT)["sheets"][1]["text"].update(sha256="a"))),
        ("E3", "part_text left the view elsewhere",
         lambda b: case(b, DISTINCT)["sheets"][1]["text"].update(partAfter=1)),
        ("E3", "part_text errored", lambda b: case(b, DISTINCT)["sheets"][2].update(error={"code": "X"})),
        ("E4a", "size fields missing (undefined)",
         lambda b: case(b, DISTINCT)["sheets"][0]["tiles"][0].update(widthTwipsType="undefined")),
        ("E4a", "the second paint still says changed",
         lambda b: case(b, DISTINCT)["sheets"][0]["tiles"][1].update(documentSizeChanged=True)),
        ("E4a", "a content sheet painted as the empty control",
         lambda b: case(b, DISTINCT)["sheets"][0]["tiles"][0].update(sha256="empty")),
        ("E4a", "only one paint", lambda b: case(b, DISTINCT)["sheets"][0]["tiles"].pop()),
        ("E5", "distinct sheets painted alike",
         lambda b: case(b, DISTINCT)["sheets"][2]["tiles"][0].update(sha256="t0")),
        ("E5", "identical sheets painted differently",
         lambda b: case(b, IDENTICAL)["sheets"][1]["tiles"][0].update(sha256="other")),
        ("E5", "the read-back echoes another part",
         lambda b: case(b, DISTINCT)["sheets"][1].update(readBack=0)),
        ("E5", "names differ from the manifest",
         lambda b: case(b, DISTINCT)["state"].update(partNames=["Sheet1", "Sheet2", "Sheet3"])),
        ("E5", "the engine accepted part `parts`",
         lambda b: case(b, DISTINCT).update(engineRefusal=None)),
        ("E6", "no destroy stage", lambda b: case(b, DISTINCT).update(stages=[{"name": "open.begin", "sbrk": 1}])),
        ("E6", "over the kill line",
         lambda b: case(b, DISTINCT)["stages"].append({"name": "x", "sbrk": KILL_LINE})),
    ]
    control = judge(base)
    results = [("control (every criterion met)", all(v["pass"] for v in control.values()),
                [k for k, v in control.items() if not v["pass"]])]
    for criterion, label, edit in mutations:
        broken = copy.deepcopy(base)
        edit(broken)
        verdicts = judge(broken)
        red = [k for k, v in verdicts.items() if not v["pass"]]
        results.append((f"{criterion}: {label}", criterion in red, red))
    for label, ok, red in results:
        print(("PASS " if ok else "FAIL ") + label + (f"  red={red}" if red else ""))
    passed = sum(ok for _, ok, _ in results)
    print(f"selftest: {passed}/{len(results)}")
    return 0 if passed == len(results) else 1


