def sha256_bytes(data: bytes) -> str:
    return hashlib.sha256(data).hexdigest()


def text_sha(text: str) -> str:
    return sha256_bytes(text.replace("\r\n", "\n").encode("utf-8"))


def utc_now() -> str:
    return datetime.now(timezone.utc).strftime("%Y-%m-%dT%H%M%SZ")


def oracle_texts() -> dict[str, list]:
    """basename-relative path -> the native oracle's sheet list."""
    out = {}
    for line in ORACLE.read_text(encoding="utf-8").splitlines():
        if line.strip():
            record = json.loads(line)
            rel = str(Path(record["file"]).resolve().relative_to(CORPUS.resolve()))
            out[rel] = record.get("sheets") or []
    return out


# Spec addendum 7 (A7.2, A7.3): two properties of a sheet that the manifest does not carry, derived
# from the file itself.  Hidden: its table style says table:display="false" (Calc cannot switch to
# it, so E3/E4a skip it and E5 expects a refusal).  Volatile: a formula in it calls a function whose
# value depends on the day or on chance, or it holds a date/time text field (the oracle's text is
# then a function of its run date, so E3 records the comparison instead of judging it).
VOLATILE_RE = re.compile(r"\b(?:TODAY|NOW|RAND|RANDBETWEEN|RAND\.NV|RANDBETWEEN\.NV)\s*\(", re.IGNORECASE)
STYLE_RE = re.compile(r"<style:style\b([^>]*)>(.*?)</style:style>", re.DOTALL)
TABLE_START_RE = re.compile(r"<table:table\s")


def sheet_properties(path: Path) -> dict:
    """{'hiddenParts': [...], 'volatileParts': [...], 'tables': n} from content.xml, in part order."""
    try:
        with zipfile.ZipFile(path) as package:
            content = package.read("content.xml").decode("utf-8", "replace")
    except Exception as error:  # noqa: BLE001 - an unreadable package (encrypted) has no parts to classify
        return {"hiddenParts": [], "volatileParts": [], "tables": None, "sheetPropertiesError": str(error)[:120]}
    hidden_styles = {re.search(r'style:name="([^"]+)"', attrs).group(1)
                     for attrs, body in STYLE_RE.findall(content)
                     if 'style:family="table"' in attrs and 'table:display="false"' in body
                     and re.search(r'style:name="([^"]+)"', attrs)}
    starts = [m.start() for m in TABLE_START_RE.finditer(content)]
    end = content.find("</office:spreadsheet>")
    chunks = [content[start:(starts[i + 1] if i + 1 < len(starts) else (end if end > start else len(content)))]
              for i, start in enumerate(starts)]
    # A cached external-link sheet is stored as a <table:table> with a <table:table-source> child and
    # is not a part of the document (10 corpus files carry one); only the real tables are numbered.
    chunks = [c for c in chunks if "<table:table-source" not in c]
    hidden, volatile = [], []
    for k, chunk in enumerate(chunks):
        tag = chunk[:chunk.find(">") + 1]
        style = re.search(r'table:style-name="([^"]+)"', tag)
        if style and style.group(1) in hidden_styles:
            hidden.append(k)
        formulas = re.findall(r'table:formula="([^"]*)"', chunk)
        if any(VOLATILE_RE.search(f) for f in formulas) or "<text:date" in chunk or "<text:time" in chunk:
            volatile.append(k)
    return {"hiddenParts": hidden, "volatileParts": volatile, "tables": len(chunks),
            "externalCacheTables": len(starts) - len(chunks),
            # Addendum 8 (finding 158, 158-A): a control shape; the session refuses such a file.
            "formControls": "<draw:control" in content}


def expected_sheets(entry: dict, oracle: dict) -> list[dict]:
    """Per part: name and the expected text's sha (None when nothing is expected)."""
    names = entry.get("sheetNames") or []
    texts = entry.get("expectedText") or {}
    sheets = []
    for k, name in enumerate(names):
        text = texts.get(name)
        if text is None:
            native = oracle.get(entry["path"]) or []
            text = native[k]["text"] if k < len(native) else None
            text = "" if text is None and k < len(native) else text
        sheets.append({"name": name, "textSha256": text_sha(text) if text is not None else None,
                       "textLength": len(text.replace("\r\n", "\n")) if text is not None else None,
                       "empty": text == ""})
    return sheets


# ---------------------------------------------------------------- judges --
def verdict(identifier: str, ok: bool, detail) -> dict:
    return {"id": identifier, "ok": bool(ok), "detail": detail}


def judge_e1(report: dict) -> list[dict]:
    """Form 2: closure of the corpus, the manifest and the report, keyed by sha256."""
    staged = report.get("staged") or []
    files = report.get("corpusFiles") or {}
    entries = {e["path"]: e for e in report.get("manifestEntries") or []}
    cases = [c for c in report.get("cases") or [] if c.get("kind") == "corpus"]
    problems = []
    if not files:
        problems.append("the corpus directory listed no file")
    for path, sha in files.items():
        if path not in entries:
            problems.append(f"{path}: no manifest entry")
        elif entries[path]["sha256"] != sha:
            problems.append(f"{path}: manifest sha differs")
    for path in entries:
        if path not in files:
            problems.append(f"{path}: manifest entry without a file")
    staged_shas = sorted(s["sha256"] for s in staged)
    case_shas = sorted(c.get("inputSha256") or "" for c in cases)
    if staged_shas != case_shas:
        problems.append(f"{len(staged_shas)} entries staged, the report has {len(case_shas)} matching records")
    if report.get("fullCorpus") and len(staged) != len(entries):
        problems.append(f"a full run staged {len(staged)} of {len(entries)} entries")
    return [verdict("E1", not problems, problems[:20])]


def staged_for(report: dict) -> dict:
    return {s["sha256"]: s for s in report.get("staged") or []}


def corpus_cases(report: dict):
    by_sha = staged_for(report)
    for case in report.get("cases") or []:
        if case.get("kind") == "corpus":
            yield case, by_sha.get(case.get("inputSha256"))


def declares(report: dict, capability: str) -> bool:
    return capability in (report.get("profileCapabilities") or [])


def judge_e2(report: dict) -> list[dict]:
    out = []
    forms = declares(report, "form-controls")
    for case, staged in corpus_cases(report):
        name = (staged or {}).get("path") or case.get("name")
        if staged is None:
            out.append(verdict(f"E2 {name}", False, "no staged entry for this record"))
            continue
        state = case.get("state") or {}
        fields = case.get("handleFields") or {}
        if staged["expect"] == "refused":
            ok = ((case.get("refused") or {}).get("code") == "ENCRYPTED_DOCUMENT"
                  and case.get("engineCreated") is False)
            out.append(verdict(f"E2 {name}", ok, {"refused": case.get("refused"),
                                                  "engineCreated": case.get("engineCreated")}))
            continue
        if staged.get("formControls") and not forms:
            # Addendum 8 A8.3: derived from the file, this overrides the manifest's `opens` (which
            # says the native oracle opened it): the viewer must refuse it, typed, with no engine.
            ok = ((case.get("refused") or {}).get("code") == "FORM_CONTROLS_UNSUPPORTED"
                  and case.get("engineCreated") is False)
            out.append(verdict(f"E2 {name}", ok, {"formControls": True, "refused": case.get("refused"),
                                                  "engineCreated": case.get("engineCreated")}))
            continue
        ok = (bool(case.get("opened")) and not case.get("error") and not case.get("refused")
              and not case.get("workerCrashed")
              and isinstance(case.get("viewReadyAtMs"), int) and case["viewReadyAtMs"] <= VIEW_READY_MS
              and fields.get("documentType") == "spreadsheet" and state.get("documentType") == "spreadsheet"
              and state.get("parts") == staged["sheets"] and fields.get("inputSuffix") == ".ods"
              and state.get("nameSpoofed") is False)
        out.append(verdict(f"E2 {name}", ok, {
            "viewReadyAtMs": case.get("viewReadyAtMs"), "documentType": fields.get("documentType"),
            "parts": state.get("parts"), "expected": staged["sheets"], "inputSuffix": fields.get("inputSuffix"),
            "nameSpoofed": state.get("nameSpoofed"), "error": case.get("error"), "refused": case.get("refused")}))
    control = [c for c in report.get("cases") or [] if c.get("kind") == "control-odt"]
    c = control[0] if control else {}
    out.append(verdict("E2 negative control (an ODT through the viewer)",
                       (c.get("refused") or {}).get("code") == "DOCUMENT_TYPE_REFUSED"
                       and (c.get("handleFields") or {}).get("documentType") == "text",
                       {"refused": c.get("refused"), "documentType": (c.get("handleFields") or {}).get("documentType")}))
    if not any(True for _ in corpus_cases(report)):
        out.append(verdict("E2 non-empty", False, "no corpus record"))
    return out


def opened_cases(report: dict):
    forms = declares(report, "form-controls")      # SPEC-M4-viewer-v2 4, V2-158B
    for case, staged in corpus_cases(report):
        if (staged and staged["expect"] == "opens" and (forms or not staged.get("formControls"))
                and case.get("opened")):
            yield case, staged


def hidden_parts(staged: dict) -> set:
    return set(staged.get("hiddenParts") or [])


def judge_e3(report: dict) -> list[dict]:
    out = []
    for case, staged in opened_cases(report):
        sheets = case.get("sheets") or []
        want = staged["expectedSheets"]
        hidden = hidden_parts(staged)
        volatile = set(staged.get("volatileParts") or [])
        problems, recorded = [], []
        if len(sheets) != len(want):
            problems.append(f"{len(sheets)} sheets read, {len(want)} expected")
        for got, exp in zip(sheets, want):
            k = got["part"]
            if k in hidden:                                   # A7.2: Calc cannot show it
                continue
            t = got.get("text") or {}
            problem = None
            if got.get("error"):
                problem = f"part {k}: {got['error']}"
            elif exp["textSha256"] is None:
                problem = f"part {k}: no expected text"
            elif t.get("sha256") != exp["textSha256"]:
                problem = (f"part {k}: text differs ({t.get('length')} chars, "
                           f"expected {exp['textLength']}; selectAllConfirmed {t.get('selectAllConfirmed')})")
            elif t.get("partAfter") != t.get("currentPartBefore"):
                problem = f"part {k}: part_text left the view on {t.get('partAfter')}, not {t.get('currentPartBefore')}"
            if problem is None:
                continue
            if k in volatile and not got.get("error"):         # A7.3: recorded, not judged
                recorded.append(problem)
            else:
                problems.append(problem)
        out.append(verdict(f"E3 {staged['path']}", not problems and bool(sheets),
                           problems[:5] if problems else ({"recorded": recorded[:5]} if recorded else [])))
    return out


def empty_control_tile(report: dict) -> str | None:
    for case, staged in opened_cases(report):
        if staged["path"] == EMPTY_CONTROL and case.get("sheets"):
            tiles = case["sheets"][0].get("tiles") or []
            return tiles[0]["sha256"] if tiles else None
    return None


def judge_e4a(report: dict) -> list[dict]:
    """Engine half.  The control comparison applies where the manifest can say what is in the first
    tile: a generated (ladder) entry writes from A1, so cells > 0 means content there; an expected text
    of "" means an empty sheet.  An upstream entry's manifest makes no claim about where its cells are,
    so for it only the paint and size clauses apply (spec addendum 5)."""
    out = []
    empty = empty_control_tile(report)
    out.append(verdict("E4a the empty control was painted", empty is not None, empty))
    for case, staged in opened_cases(report):
        problems = []
        for sheet, exp in zip(case.get("sheets") or [], staged["expectedSheets"]):
            if sheet["part"] in hidden_parts(staged):            # A7.2
                continue
            tiles = sheet.get("tiles") or []
            if len(tiles) != 2:
                problems.append(f"part {sheet['part']}: {len(tiles)} paints, want 2 ({sheet.get('error')})")
                continue
            first, second = tiles
            if (first["widthTwipsType"], first["heightTwipsType"], first["sizeChangedType"]) != \
                    ("number", "number", "boolean"):
                problems.append(f"part {sheet['part']}: size fields typed "
                                f"{first['widthTwipsType']}/{first['heightTwipsType']}/{first['sizeChangedType']}")
            if second["documentSizeChanged"] is not False:
                problems.append(f"part {sheet['part']}: the second paint says documentSizeChanged "
                                f"{second['documentSizeChanged']}")
            if empty is not None and staged["expectedFrom"] == "generator":
                if exp["empty"] and first["sha256"] != empty:
                    problems.append(f"part {sheet['part']}: an empty sheet's tile differs from the empty control")
                if not exp["empty"] and (staged.get("cells") or 0) > 0 and first["sha256"] == empty:
                    problems.append(f"part {sheet['part']}: a sheet with content painted as the empty control")
        out.append(verdict(f"E4a {staged['path']}", not problems and bool(case.get("sheets")), problems[:5]))
    return out


def judge_e5(report: dict) -> list[dict]:
    out = []
    firsts = {}
    v2 = declares(report, "part-info")
    for case, staged in opened_cases(report):
        problems = []
        names = (case.get("state") or {}).get("partNames")
        if names != staged["sheetNames"]:
            problems.append(f"part names {names} != {staged['sheetNames']}")
        for sheet in case.get("sheets") or []:
            sw = sheet.get("switch") or {}
            if sheet["part"] in hidden_parts(staged):
                # A7.2: a hidden sheet is never shown -- the session refuses and the engine is not on it.
                if not sheet.get("error") or sw.get("readBack") == sheet["part"] or sheet.get("readBack") == sheet["part"]:
                    problems.append(f"hidden part {sheet['part']} was shown or not refused: {sheet.get('error')}")
                elif v2 and ((sheet.get("error") or {}).get("code") != "PART_HIDDEN" or sheet.get("setPartCalls") != 0
                             or sheet.get("readBackAfterError") == sheet["part"]):
                    # SPEC-M4-viewer-v2 4 (V2-157): refused by the session, before the engine.
                    problems.append(f"hidden part {sheet['part']}: {sheet.get('error')}, "
                                    f"{sheet.get('setPartCalls')} switches reached the handle, "
                                    f"engine on {sheet.get('readBackAfterError')}")
                continue
            if sw.get("readBack") != sheet["part"] or sheet.get("readBack") != sheet["part"]:
                problems.append(f"switch to {sheet['part']}: read back {sw.get('readBack')}/{sheet.get('readBack')}")
        reselect = case.get("reselect") or {}
        if reselect.get("readBack") != reselect.get("current") or "current" not in reselect:
            problems.append(f"re-selecting the current part read back {reselect}")
        if (case.get("sessionRefusal") or {}).get("code") != "PART_OUT_OF_RANGE":
            problems.append(f"the session's refusal of part {staged['sheets']}: {case.get('sessionRefusal')}")
        if (case.get("engineRefusal") or {}).get("code") != "INVALID_ARGUMENT":
            problems.append(f"the engine's refusal of part {staged['sheets']}: {case.get('engineRefusal')}")
        if case.get("afterRefusals") != reselect.get("current"):
            problems.append(f"after the refusals the engine is on {case.get('afterRefusals')}")
        out.append(verdict(f"E5 {staged['path']}", not problems, problems[:5]))
        firsts[staged["path"]] = [(s.get("tiles") or [{}])[0].get("sha256") for s in case.get("sheets") or []]
    for path, want_distinct in ((DISTINCT, True), (IDENTICAL, False)):
        tiles = firsts.get(path)
        ok = bool(tiles) and len(tiles) == 3 and None not in tiles and (
            len(set(tiles)) == 3 if want_distinct else len(set(tiles)) == 1)
        out.append(verdict(f"E5 {path} tiles {'pairwise distinct' if want_distinct else 'identical'}",
                           ok, [t[:12] if t else t for t in tiles or []]))
    return out


def judge_e6(report: dict) -> list[dict]:
    out = []
    for case, staged in opened_cases(report):
        stages = [s for s in case.get("stages") or [] if isinstance(s.get("sbrk"), int)]
        peak = max((s["sbrk"] for s in stages), default=None)
        destroyed = any(s.get("name") == "document-destroy-enter" for s in stages)
        out.append(verdict(f"E6 {staged['path']}", peak is not None and peak < KILL_LINE and destroyed,
                           {"peakSbrk": peak, "destroyEnterSeen": destroyed, "stages": len(stages)}))
    return out


def judge_v2_157(report: dict) -> list[dict]:
    """SPEC-M4-viewer-v2 4: what the engine says is visible is what the file says, part by part."""
    out = []
    for case, staged in opened_cases(report):
        state = case.get("state") or {}
        want = [k not in hidden_parts(staged) for k in range(staged["sheets"])]
        tabs = state.get("tabs") or []
        problems = []
        if state.get("partVisible") != want:
            problems.append(f"partVisible {state.get('partVisible')} != {want} ({state.get('partVisibilityProblem')})")
        for k, visible in enumerate(want):
            tab = tabs[k] if k < len(tabs) else {}
            if not visible and (tab.get("enabled") is not False or tab.get("hidden") is not True):
                problems.append(f"hidden part {k}'s tab: {tab}")
        out.append(verdict(f"V2-157 {staged['path']}", not problems, problems[:5]))
    return out


def judge_v2_158b(report: dict) -> list[dict]:
    """SPEC-M4-viewer-v2 4: the files with a form control, listed, each opened (E2-E4a judge them)."""
    out = []
    for case, staged in corpus_cases(report):
        if staged and staged.get("formControls"):
            out.append(verdict(f"V2-158B {staged['path']}", bool(case.get("opened")) and case.get("engineCreated"),
                               {"opened": case.get("opened"), "refused": case.get("refused"),
                                "formControlsDrawable": (case.get("state") or {}).get("formControlsDrawable")}))
    if not out:
        out.append(verdict("V2-158B non-empty", False, "no staged file carries a form control"))
    return out


def judge_v2_160(report: dict) -> list[dict]:
    """SPEC-M4-viewer-v2 4: every SelectAll confirmed; the wait distribution recorded."""
    waits, late, unconfirmed = [], 0, []
    for case, staged in opened_cases(report):
        for sheet in case.get("sheets") or []:
            text = sheet.get("text") or {}
            if not text:
                continue
            if isinstance(text.get("selectAllWaitMs"), int):
                waits.append(text["selectAllWaitMs"])
            late += text.get("lateSelectAllResults") or 0
            if text.get("selectAllConfirmed") is not True:
                unconfirmed.append(f"{staged['path']} part {sheet['part']}")
    waits.sort()
    p99 = waits[min(len(waits) - 1, int(len(waits) * 0.99))] if waits else None
    detail = {"reads": len(waits), "unconfirmed": unconfirmed[:20], "waitMsMax": waits[-1] if waits else None,
              "waitMsP99": p99, "lateSelectAllResults": late}
    return [verdict("V2-160", not unconfirmed and bool(waits), detail)]


JUDGES = {"E1": judge_e1, "E2": judge_e2, "E3": judge_e3, "E4a": judge_e4a, "E5": judge_e5, "E6": judge_e6}
# Only for a profile that declares the capability: an empty verdict list is a FAIL by judge().
V2_JUDGES = {"V2-157": ("part-info", judge_v2_157), "V2-158B": ("form-controls", judge_v2_158b),
             "V2-160": ("part-info", judge_v2_160)}


def judge(report: dict) -> dict:
    results = {name: fn(report) for name, fn in JUDGES.items()}
    results.update({name: fn(report) for name, (capability, fn) in V2_JUDGES.items() if declares(report, capability)})
    return {name: {"pass": all(v["ok"] for v in vs) and bool(vs), "failed": [v for v in vs if not v["ok"]],
                   "count": len(vs)} for name, vs in results.items()}


