def synthetic() -> dict:
    tile = lambda sha: {"sha256": sha, "widthTwipsType": "number", "heightTwipsType": "number",  # noqa: E731
                        "sizeChangedType": "boolean", "documentSizeChanged": False}
    def sheet(k, text_sha, tile_sha):
        return {"part": k, "switch": {"readBack": k}, "readBack": k, "error": None,
                "text": {"sha256": text_sha, "length": 1, "partAfter": 0, "currentPartBefore": 0,
                         "selectAllConfirmed": True},
                "tiles": [tile(tile_sha), {**tile(tile_sha), "documentSizeChanged": False}]}
    def opened(path, names, sheets):
        return {"kind": "corpus", "name": Path(path).name, "inputSha256": "sha-" + path, "engineCreated": True,
                "opened": {"atMs": 900}, "viewReadyAtMs": 900, "workerCrashed": False, "error": None,
                "refused": None, "state": {"documentType": "spreadsheet", "parts": len(names),
                                           "partNames": names, "nameSpoofed": False},
                "handleFields": {"documentType": "spreadsheet", "inputSuffix": ".ods"},
                "sheets": sheets, "reselect": {"current": 0, "readBack": 0}, "afterRefusals": 0,
                "sessionRefusal": {"code": "PART_OUT_OF_RANGE"}, "engineRefusal": {"code": "INVALID_ARGUMENT"},
                "stages": [{"name": "open.begin", "sbrk": 293_000_000},
                           {"name": "document-destroy-enter", "sbrk": 300_000_000}]}
    def staged(path, names, texts, expect="opens", cells=1, form_controls=False):
        return {"path": path, "sha256": "sha-" + path, "sheets": len(names), "sheetNames": names,
                "expect": expect, "expectedFrom": "generator", "cells": cells,
                "hiddenParts": [], "volatileParts": [], "formControls": form_controls,
                "expectedSheets": [{"name": n, "textSha256": t, "textLength": 1, "empty": t == "E"}
                                   for n, t in zip(names, texts)]}
    report = {
        "fullCorpus": False,
        "corpusFiles": {"ladder/empty-one-sheet.ods": "sha-ladder/empty-one-sheet.ods",
                        DISTINCT: "sha-" + DISTINCT, IDENTICAL: "sha-" + IDENTICAL,
                        HIDDEN_CASE: "sha-" + HIDDEN_CASE, CONTROLS_CASE: "sha-" + CONTROLS_CASE,
                        "upstream/password.ods": "sha-upstream/password.ods"},
        "manifestEntries": [{"path": p, "sha256": "sha-" + p} for p in
                            ("ladder/empty-one-sheet.ods", DISTINCT, IDENTICAL, HIDDEN_CASE, CONTROLS_CASE,
                             "upstream/password.ods")],
        "staged": [staged(EMPTY_CONTROL, ["Sheet1"], ["E"], cells=0),
                   staged(DISTINCT, ["Alpha", "Beta", "Gamma"], ["a", "b", "c"]),
                   staged(IDENTICAL, ["One", "Two", "Three"], ["s", "s", "s"]),
                   staged(HIDDEN_CASE, ["Jan", "Feb", "Table"], ["j", "f", "x"]),
                   # The manifest says `opens` (the native oracle did); the file carries a control.
                   staged(CONTROLS_CASE, ["Form"], ["c"], form_controls=True),
                   staged("upstream/password.ods", [], [], expect="refused")],
        "cases": [opened(EMPTY_CONTROL, ["Sheet1"], [sheet(0, "E", "empty")]),
                  opened(DISTINCT, ["Alpha", "Beta", "Gamma"],
                         [sheet(0, "a", "t0"), sheet(1, "b", "t1"), sheet(2, "c", "t2")]),
                  opened(IDENTICAL, ["One", "Two", "Three"],
                         [sheet(0, "s", "same"), sheet(1, "s", "same"), sheet(2, "s", "same")]),
                  opened(HIDDEN_CASE, ["Jan", "Feb", "Table"],
                         [sheet(0, "j", "h0"), sheet(1, "f", "h1"), sheet(2, "x", "h2")]),
                  {"kind": "corpus", "name": "controls.ods", "inputSha256": "sha-" + CONTROLS_CASE,
                   "engineCreated": False, "opened": None, "refused": {"code": "FORM_CONTROLS_UNSUPPORTED"}},
                  {"kind": "corpus", "name": "password.ods", "inputSha256": "sha-upstream/password.ods",
                   "engineCreated": False, "refused": {"code": "ENCRYPTED_DOCUMENT"}},
                  {"kind": "control-odt", "refused": {"code": "DOCUMENT_TYPE_REFUSED"},
                   "handleFields": {"documentType": "text"}}],
    }
    # The switch read-backs of the synthetic sheets follow their part; partAfter is the part before.
    return report


def selftest() -> int:
    base = synthetic()

    def case(b, path):
        return next(c for c in b["cases"] if c.get("inputSha256") == "sha-" + path)

    def stg(b, path):
        return next(s for s in b["staged"] if s["path"] == path)

    def hide_part_2(b, refused=True):
        # A7.2's measured shape: the session refused the switch and the engine stayed where it was.
        stg(b, HIDDEN_CASE)["hiddenParts"] = [2]
        if refused:
            case(b, HIDDEN_CASE)["sheets"][2] = {"part": 2, "switch": None, "readBack": None, "text": None,
                                                 "tiles": [], "error": {"code": "PART_READBACK_MISMATCH"}}

    mutations = [
        ("E5", "a hidden part was shown (no refusal, read back is it)", lambda b: hide_part_2(b, refused=False)),
        ("E2", "a file with a form control was opened (A8.3)",
         lambda b: case(b, CONTROLS_CASE).update(refused=None, engineCreated=True, opened={"atMs": 1},
                                                 state={"documentType": "spreadsheet", "parts": 1},
                                                 handleFields={"documentType": "spreadsheet", "inputSuffix": ".ods"})),
        ("E2", "a file with a form control was refused generically (A8.3)",
         lambda b: case(b, CONTROLS_CASE).update(refused={"code": "LOK_ERROR"})),
        ("E2", "a file with a form control reached an engine before the refusal (A8.3)",
         lambda b: case(b, CONTROLS_CASE).update(engineCreated=True)),
        ("E1", "a corpus file without a manifest entry",
         lambda b: b["corpusFiles"].update({"ladder/zzz.ods": "sha-z"})),
        ("E1", "an empty corpus directory", lambda b: b.update(corpusFiles={})),
        ("E1", "a staged entry with no record", lambda b: b["cases"].pop(1)),
        ("E2", "the ODT control passes as a spreadsheet",
         lambda b: b["cases"][-1].update(refused=None, handleFields={"documentType": "spreadsheet"})),
        ("E2", "the three-sheet file reports 1 part", lambda b: case(b, DISTINCT)["state"].update(parts=1)),
        ("E2", "the name was spoofed", lambda b: case(b, DISTINCT)["state"].update(nameSpoofed=True)),
        ("E2", "the input file was .odt", lambda b: case(b, DISTINCT)["handleFields"].update(inputSuffix=".odt")),
        ("E2", "view-ready after 60 s", lambda b: case(b, DISTINCT).update(viewReadyAtMs=60_001)),
        ("E2", "the encrypted file reached an engine",
         lambda b: case(b, "upstream/password.ods").update(engineCreated=True)),
        ("E2", "the encrypted file refused generically",
         lambda b: case(b, "upstream/password.ods").update(refused={"code": "LOK_ERROR"})),
        ("E3", "two sheets' texts swapped", lambda b: (
            case(b, DISTINCT)["sheets"][0]["text"].update(sha256="b"),
            case(b, DISTINCT)["sheets"][1]["text"].update(sha256="a"))),
        ("E3", "part_text left the view elsewhere",
         lambda b: case(b, DISTINCT)["sheets"][1]["text"].update(partAfter=1)),
        ("E3", "part_text errored", lambda b: case(b, DISTINCT)["sheets"][2].update(error={"code": "X"})),
        ("E4a", "size fields missing (undefined)",
         lambda b: case(b, DISTINCT)["sheets"][0]["tiles"][0].update(widthTwipsType="undefined")),
        ("E4a", "the second paint still says changed",
         lambda b: case(b, DISTINCT)["sheets"][0]["tiles"][1].update(documentSizeChanged=True)),
        ("E4a", "a content sheet painted as the empty control",
         lambda b: case(b, DISTINCT)["sheets"][0]["tiles"][0].update(sha256="empty")),
        ("E4a", "only one paint", lambda b: case(b, DISTINCT)["sheets"][0]["tiles"].pop()),
        ("E5", "distinct sheets painted alike",
         lambda b: case(b, DISTINCT)["sheets"][2]["tiles"][0].update(sha256="t0")),
        ("E5", "identical sheets painted differently",
         lambda b: case(b, IDENTICAL)["sheets"][1]["tiles"][0].update(sha256="other")),
        ("E5", "the read-back echoes another part",
         lambda b: case(b, DISTINCT)["sheets"][1].update(readBack=0)),
        ("E5", "names differ from the manifest",
         lambda b: case(b, DISTINCT)["state"].update(partNames=["Sheet1", "Sheet2", "Sheet3"])),
        ("E5", "the engine accepted part `parts`",
         lambda b: case(b, DISTINCT).update(engineRefusal=None)),
        ("E6", "no destroy stage", lambda b: case(b, DISTINCT).update(stages=[{"name": "open.begin", "sbrk": 1}])),
        ("E6", "over the kill line",
         lambda b: case(b, DISTINCT)["stages"].append({"name": "x", "sbrk": KILL_LINE})),
    ]
    control = judge(base)
    results = [("control (every criterion met)", all(v["pass"] for v in control.values()),
                [k for k, v in control.items() if not v["pass"]])]
    v2_named = [k for k in control if k.startswith("V2-")]
    results.append(("control: v1 readings run no V2 judge", not v2_named, v2_named))

    # SPEC-M4-viewer-v2 4: the same corpus judged as ods-viewer-v2 (part-info, form-controls).
    def as_v2(b):
        b["profileCapabilities"] = ["open-odt", "rgba-tile", "cancel-queued", "search", "open-ods",
                                    "part-switch", "part-text", "part-info", "form-controls"]
        stg(b, HIDDEN_CASE)["hiddenParts"] = [2]
        for c in b["cases"]:
            if c.get("kind") == "corpus" and c.get("opened"):
                parts = c["state"]["parts"]
                c["state"]["partVisible"] = [True] * parts
                c["state"]["tabs"] = [{"index": k, "enabled": True, "hidden": False} for k in range(parts)]
                for s in c["sheets"]:
                    s["setPartCalls"] = 1
                    s["text"].update(selectAllWaitMs=20, lateSelectAllResults=0)
        hidden = case(b, HIDDEN_CASE)
        hidden["state"]["partVisible"] = [True, True, False]
        hidden["state"]["tabs"][2] = {"index": 2, "enabled": False, "hidden": True}
        hidden["sheets"][2] = {"part": 2, "switch": None, "readBack": None, "text": None, "tiles": [],
                               "error": {"code": "PART_HIDDEN"}, "setPartCalls": 0, "readBackAfterError": 1}
        # The form-control file, opened: the empty control's record with this file's identity and text.
        controls = case(b, CONTROLS_CASE)
        opened_like = copy.deepcopy(case(b, EMPTY_CONTROL))
        opened_like.update(name="controls.ods", inputSha256="sha-" + CONTROLS_CASE)
        opened_like["state"].update(partNames=["Form"], formControlsDrawable=True)
        opened_like["sheets"][0]["text"]["sha256"] = "c"
        opened_like["sheets"][0]["tiles"] = [{**tl, "sha256": "f0"} for tl in opened_like["sheets"][0]["tiles"]]
        controls.clear()
        controls.update(opened_like)
        return b

    v2_base = as_v2(copy.deepcopy(base))
    v2_control = judge(v2_base)
    results.append(("v2 control (every criterion met, V2 judges run)",
                    all(v["pass"] for v in v2_control.values())
                    and {"V2-157", "V2-158B", "V2-160"} <= set(v2_control),
                    [k for k, v in v2_control.items() if not v["pass"]]
                    or sorted({"V2-157", "V2-158B", "V2-160"} - set(v2_control))))
    v2_mutations = [
        ("E5", "v2: a hidden part refused the v1 way (the engine was asked)",
         lambda b: case(b, HIDDEN_CASE)["sheets"][2].update(error={"code": "PART_READBACK_MISMATCH"}, setPartCalls=1)),
        ("E5", "v2: PART_HIDDEN, but a switch reached the handle",
         lambda b: case(b, HIDDEN_CASE)["sheets"][2].update(setPartCalls=1)),
        ("V2-157", "v2: the engine says the hidden part is visible",
         lambda b: case(b, HIDDEN_CASE)["state"].update(partVisible=[True, True, True])),
        ("V2-157", "v2: no partVisible (the adapter fell back)",
         lambda b: case(b, DISTINCT)["state"].update(partVisible=None)),
        ("V2-157", "v2: the hidden part's tab is enabled",
         lambda b: case(b, HIDDEN_CASE)["state"]["tabs"][2].update(enabled=True)),
        ("E2", "v2: the form-control file was still refused",
         lambda b: case(b, CONTROLS_CASE).update(opened=None, refused={"code": "FORM_CONTROLS_UNSUPPORTED"},
                                                 engineCreated=False)),
        ("V2-158B", "v2: the form-control file was still refused",
         lambda b: case(b, CONTROLS_CASE).update(opened=None, refused={"code": "FORM_CONTROLS_UNSUPPORTED"},
                                                 engineCreated=False)),
        ("E3", "v2: the form-control file's text differs",
         lambda b: case(b, CONTROLS_CASE)["sheets"][0]["text"].update(sha256="other")),
        ("V2-160", "v2: one SelectAll unconfirmed",
         lambda b: case(b, DISTINCT)["sheets"][1]["text"].update(selectAllConfirmed=False)),
        ("V2-160", "v2: no wait recorded at all (a v1 engine under a v2 manifest)",
         lambda b: [s["text"].pop("selectAllWaitMs", None) for c in b["cases"] for s in c.get("sheets") or []
                    if s.get("text")]),
    ]
    for criterion, label, edit in v2_mutations:
        broken = copy.deepcopy(v2_base)
        edit(broken)
        verdicts = judge(broken)
        red = [k for k, v in verdicts.items() if not v["pass"]]
        results.append((f"{criterion}: {label}", criterion in red, red))
    # A7.2 / A7.3 controls: a hidden part that was refused and a volatile part whose text differs
    # must NOT turn E3/E4a/E5 red (the second is recorded in E3's detail).
    hidden_ok = copy.deepcopy(base)
    hide_part_2(hidden_ok)
    v = judge(hidden_ok)
    results.append(("control: a hidden part refused passes E3/E4a/E5", all(x["pass"] for x in v.values()),
                    [k for k, x in v.items() if not x["pass"]]))
    volatile_ok = copy.deepcopy(base)
    stg(volatile_ok, DISTINCT)["volatileParts"] = [1]
    case(volatile_ok, DISTINCT)["sheets"][1]["text"]["sha256"] = "today"
    e3 = judge_e3(volatile_ok)
    recorded = next((x["detail"] for x in e3 if x["id"] == f"E3 {DISTINCT}"), None)
    results.append(("control: a volatile part's differing text is recorded, not red",
                    all(x["ok"] for x in e3) and isinstance(recorded, dict) and bool(recorded.get("recorded")), []))
    for criterion, label, edit in mutations:
        broken = copy.deepcopy(base)
        edit(broken)
        verdicts = judge(broken)
        red = [k for k, v in verdicts.items() if not v["pass"]]
        results.append((f"{criterion}: {label}", criterion in red, red))
    for label, ok, red in results:
        print(("PASS " if ok else "FAIL ") + label + (f"  red={red}" if red else ""))
    passed = sum(ok for _, ok, _ in results)
    print(f"selftest: {passed}/{len(results)}")
    return 0 if passed == len(results) else 1


