def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--selftest", action="store_true")
    parser.add_argument("--profile", choices=PROFILES, default=PROFILE)
    parser.add_argument("--only", action="append", default=None,
                        help="stage only corpus entries whose path starts with this (repeatable)")
    parser.add_argument("--record-text", action="store_true",
                        help="diagnostic: the harness keeps each sheet's text (<= 20000 chars), not only its sha")
    parser.add_argument("--out", type=Path, default=DEFAULT_OUT)
    parser.add_argument("--timeout", type=float, default=7200)
    args = parser.parse_args()
    if args.selftest:
        return selftest()
    gate = preconditions()
    if gate["wallet"] != "b false":
        raise SystemExit(f"the KDE wallet is locked ({gate['wallet']!r}): headless Chrome would hang")
    profile_manifest = PROJECT / "dist" / "profiles" / args.profile / "sdk-manifest.json"
    if not profile_manifest.is_file():
        raise SystemExit(f"{profile_manifest} does not exist: the viewer is not linked")

    from r7_support import evaluate, wait_page                      # noqa: E402
    from run_browser_probe import ChromeSession, free_port          # noqa: E402
    from run_e2_c_page_smoke import navigate                        # noqa: E402
    from run_e2_c_product_path import build_mirror                  # noqa: E402

    manifest = json.loads(MANIFEST.read_text(encoding="utf-8"))
    oracle = oracle_texts()
    corpus_files = {str(p.relative_to(CORPUS)): sha256_bytes(p.read_bytes())
                    for p in sorted(CORPUS.rglob("*.ods"))}
    picked = [e for e in manifest["entries"]
              if args.only is None or any(e["path"].startswith(prefix) for prefix in args.only)]
    if args.only:
        # The three ladder controls ride along on every partial run: the empty control for E4a, the
        # distinct and identical pair for E5 (A7.5: without them E5 was red with an empty detail).
        for control in (IDENTICAL, DISTINCT, EMPTY_CONTROL):
            if not any(e["path"] == control for e in picked):
                picked.insert(0, next(e for e in manifest["entries"] if e["path"] == control))
    if not picked:
        raise SystemExit("nothing staged: a run over zero entries must be red, not empty")

    overrides = {path: source.read_bytes() for path, source in PAGE_FILES.items() if path.startswith("viewer-shell/")}
    overrides.update({path: source.read_bytes() for path, source in HARNESS.items()})
    if args.profile != PROFILE:
        # The page's one worker literal, rewritten in the mirror copy only (as v1 was before its link).
        app = overrides["ods-viewer-e-harness-app.js"]
        if app.count(HARNESS_LITERAL) != 1:
            raise SystemExit(f"the harness page has {app.count(HARNESS_LITERAL)} worker literals, not 1")
        overrides["ods-viewer-e-harness-app.js"] = app.replace(
            HARNESS_LITERAL, f'"./profiles/{args.profile}/sdk-worker.js"'.encode())
    staged, specs = [], []
    for index, entry in enumerate(picked):
        source = CORPUS / entry["path"]
        rel = f"ods-e-cases/{index:03d}/{Path(entry['path']).name}"
        overrides[rel] = source.read_bytes()
        specs.append({"name": Path(entry["path"]).name, "file": "./" + rel, "kind": "corpus"})
        staged.append({**{k: entry[k] for k in ("path", "sha256", "sheets", "sheetNames", "expect",
                                                "expectedFrom", "cells")},
                       **sheet_properties(source),
                       "expectedSheets": expected_sheets(entry, oracle) if entry["expect"] == "opens" else []})
    overrides["ods-e-cases/control.odt"] = CONTROL_ODT.read_bytes()
    specs.append({"name": CONTROL_ODT.name, "file": "./ods-e-cases/control.odt", "kind": "control-odt"})
    overrides["ods-e-cases.json"] = json.dumps(specs, ensure_ascii=False).encode("utf-8")

    scratch = Path(tempfile.mkdtemp(prefix="ods-phase-e-"))
    root = scratch / "root"
    build_mirror(PROJECT / "dist", root, overrides)
    for relative, payload in overrides.items():
        target = root / relative
        if not target.exists():
            target.parent.mkdir(parents=True, exist_ok=True)
            target.write_bytes(payload)
    for relative, payload in overrides.items():
        if (root / relative).read_bytes() != payload:
            raise SystemExit(f"the mirror serves different bytes for {relative}")

    report = {"schemaVersion": 1, "release": "m4-ods-phase-e", "spec": "specs/SPEC-M4-ods-in-nextcloud.md §4",
              "startedAt": utc_now(), "profile": args.profile, "preconditions": gate,
              "profileCapabilities": json.loads(profile_manifest.read_text(encoding="utf-8")).get("capabilities"),
              "profileManifestSha256": sha256_bytes(profile_manifest.read_bytes()),
              "probeWasmSha256": sha256_bytes((profile_manifest.parent / "probe.wasm").read_bytes()),
              "workerSha256": sha256_bytes((profile_manifest.parent / "sdk-worker.js").read_bytes()),
              "pageFiles": {p: sha256_bytes(b) for p, b in overrides.items() if not p.startswith("ods-e-cases")},
              "fullCorpus": args.only is None, "only": args.only, "recordText": args.record_text,
              "evidenceClass": "diagnostic" if args.record_text else "gate", "corpusFiles": corpus_files,
              "manifestEntries": [{"path": e["path"], "sha256": e["sha256"]} for e in manifest["entries"]],
              "staged": staged, "controlOdt": {"path": str(CONTROL_ODT.relative_to(PROJECT)),
                                               "sha256": sha256_bytes(CONTROL_ODT.read_bytes())},
              "cases": []}
    session = server = None
    started = time.monotonic()
    try:
        port = free_port()
        server = subprocess.Popen([sys.executable, str(PROJECT / "web" / "serve.py"), "--port", str(port),
                                   "--root", str(root)], cwd=PROJECT,
                                  stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL)
        wait_page(f"http://127.0.0.1:{port}/ods-viewer-e-harness.html")
        session = ChromeSession("cold")
        report["chrome"] = session.version
        navigate(session, f"http://127.0.0.1:{port}/ods-viewer-e-harness.html?openTimeoutMs=180000"
                          + ("&recordText=1" if args.record_text else ""))
        deadline = time.monotonic() + args.timeout
        head = {}
        while time.monotonic() < deadline:
            head = evaluate(session, f"(() => {{ const r = window.{NS}; return r ? "
                                     f"{{ done: r.done, seen: r.cases.length, fatal: r.fatal }} : null; }})()") or {}
            if head.get("done"):
                break
            time.sleep(2)
        report["timedOut"] = not head.get("done")
        report["pageFatal"] = head.get("fatal")
        report["workerUrl"] = evaluate(session, f"window.{NS}.workerUrl")
        for index in range(int(head.get("seen") or 0)):
            text = evaluate(session, f"JSON.stringify(window.{NS}.cases[{index}])")
            report["cases"].append(json.loads(text) if text else {"fatal": "not retrieved"})
    finally:
        if session is not None:
            try:
                session.close()
            except Exception:  # noqa: BLE001
                pass
        if server is not None:
            server.terminate()
        shutil.rmtree(scratch, ignore_errors=True)
    report["elapsedSeconds"] = round(time.monotonic() - started, 1)
    report["verdicts"] = judge(report)
    report["completedAt"] = utc_now()
    args.out.mkdir(parents=True, exist_ok=True)
    out = args.out / f"report-{report['startedAt']}.json"
    out.write_text(json.dumps(report, indent=1, ensure_ascii=False) + "\n", encoding="utf-8")
    print(out)
    for name, v in report["verdicts"].items():
        print(f"{name}: {'PASS' if v['pass'] else 'FAIL'} ({v['count']} verdicts, {len(v['failed'])} failed)")
        for f in v["failed"][:5]:
            print(f"    {f['id']}: {json.dumps(f['detail'], ensure_ascii=False)[:240]}")
    return 0 if all(v["pass"] for v in report["verdicts"].values()) else 1


if __name__ == "__main__":
    raise SystemExit(main())
